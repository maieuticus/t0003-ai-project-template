#!/usr/bin/env python3
"""Install the project's pre-commit security hook safely."""

from pathlib import Path
import shutil
import subprocess
import sys


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        text=True,
        check=False,
    )


def main() -> int:
    root = Path(__file__).resolve().parents[1]

    if not (root / ".pre-commit-config.yaml").is_file():
        print("FEHLER: .pre-commit-config.yaml fehlt.")
        return 1

    result = git(root, "rev-parse", "--show-toplevel")
    if result.returncode or Path(result.stdout.strip()).resolve() != root:
        print("FEHLER: Kein passendes Git-Arbeitsverzeichnis.")
        return 1

    custom = git(root, "config", "--get", "core.hooksPath")
    if custom.returncode == 0 and custom.stdout.strip():
        print("FEHLER: Ein eigener core.hooksPath ist konfiguriert.")
        print("Hook-Integration muss manuell gepr?ft werden.")
        return 1

    hook_result = git(root, "rev-parse", "--git-path", "hooks/pre-commit")
    if hook_result.returncode:
        print("FEHLER: Git-Hook-Verzeichnis nicht gefunden.")
        return 1

    hook_path = Path(hook_result.stdout.strip())
    if not hook_path.is_absolute():
        hook_path = root / hook_path

    if hook_path.is_symlink():
        print("FEHLER: Vorhandener Hook ist ein symbolischer Link.")
        return 1

    if hook_path.exists():
        content = hook_path.read_text(
            encoding="utf-8", errors="replace"
        )[:1024]
        if "File generated by pre-commit" not in content:
            print("FEHLER: Fremder Pre-Commit-Hook vorhanden.")
            print("Bestehenden Hook nicht ?berschrieben.")
            return 1

    if shutil.which("gitleaks") is None:
        print("FEHLER: gitleaks nicht im PATH.")
        return 1

    available = subprocess.run(
        [sys.executable, "-m", "pre_commit", "--version"],
        capture_output=True,
        text=True,
    )
    if available.returncode:
        print("FEHLER: pre-commit ist nicht installiert.")
        print("Installation: python -m pip install --user pre-commit")
        return 1

    result = subprocess.run(
        [
            sys.executable, "-m", "pre_commit",
            "install", "--install-hooks",
            "--hook-type", "pre-commit",
        ],
        cwd=root,
        check=False,
    )

    if result.returncode:
        print("FEHLER: Hook-Installation fehlgeschlagen.")
        return result.returncode

    print("SECURITY_SETUP=OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
